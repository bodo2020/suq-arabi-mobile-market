import { readFile, writeFile } from 'node:fs/promises';

/**
 * Release build setup for Google Play (the android folder is generated, so
 * this runs on every `npm run android:sync`):
 * - versionCode / versionName come from android-release.json (bump
 *   versionCode on every upload to Play).
 * - The upload key is read from a properties file OUTSIDE the project:
 *   %USERPROFILE%\super-marko-signing\release.properties (or the path in the
 *   SUPER_MARKO_SIGNING environment variable). Keys and passwords never go
 *   into git.
 */

const appGradlePath = 'android/app/build.gradle';
const releaseGradlePath = 'android/app/release.gradle';

const releaseGradle = `// Generated by scripts/prepare-android-release.mjs — do not edit here.
import groovy.json.JsonSlurper

// SMS code autofill (SmsCodePlugin): Google SMS User Consent API.
dependencies {
    implementation "com.google.android.gms:play-services-auth-api-phone:18.1.0"
}

def releaseInfoFile = rootProject.file('../android-release.json')
if (releaseInfoFile.exists()) {
    def info = new JsonSlurper().parse(releaseInfoFile)
    android.defaultConfig.versionCode = info.versionCode as int
    android.defaultConfig.versionName = info.versionName as String
}

def signingPath = System.getenv('SUPER_MARKO_SIGNING') ?: "\${System.getProperty('user.home')}/super-marko-signing/release.properties"
def signingFile = new File(signingPath)

if (signingFile.exists()) {
    def props = new Properties()
    signingFile.withInputStream { props.load(it) }
    def keyFile = new File(props.getProperty('storeFile', ''))
    if (!keyFile.isAbsolute()) keyFile = new File(signingFile.parentFile, props.getProperty('storeFile', ''))
    android {
        signingConfigs {
            release {
                storeFile keyFile
                storePassword props.getProperty('storePassword')
                keyAlias props.getProperty('keyAlias')
                keyPassword props.getProperty('keyPassword')
            }
        }
        buildTypes {
            release {
                signingConfig signingConfigs.release
            }
        }
    }
} else {
    // Debug builds keep working; a release build without the key stops with a clear message.
    gradle.taskGraph.whenReady { graph ->
        def wantsRelease = graph.allTasks.any { t -> (t.name.startsWith('bundle') || t.name.startsWith('assemble')) && t.name.endsWith('Release') }
        if (wantsRelease) {
            throw new GradleException("Release signing file not found: \${signingPath}. See ANDROID-RELEASE.md")
        }
    }
}
`;

await writeFile(releaseGradlePath, releaseGradle, 'utf8');

let appGradle = await readFile(appGradlePath, 'utf8');
if (!appGradle.includes("apply from: 'release.gradle'")) {
  appGradle = `${appGradle.trimEnd()}\n\napply from: 'release.gradle'\n`;
  await writeFile(appGradlePath, appGradle, 'utf8');
}
console.log('Android release setup applied: version from android-release.json, upload key from outside the project.');
