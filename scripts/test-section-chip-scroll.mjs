import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source=ts.transpileModule(fs.readFileSync(new URL('../src/lib/centerSectionChip.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText;
const {centerSectionChip}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const calls=[];
const strip={getBoundingClientRect:()=>({left:10,right:310}),scrollBy:options=>calls.push(options)};
const chip=(left,right)=>({getBoundingClientRect:()=>({left,right}),scrollIntoView:()=>assert.fail('Must not move page ancestors')});
centerSectionChip(strip,chip(350,410));
centerSectionChip(strip,chip(-100,-40));
centerSectionChip(strip,chip(130,190));
assert.deepEqual(calls,[{left:220,behavior:'auto'},{left:-230,behavior:'auto'}]);
assert.ok(calls.every(call=>!('top' in call)));
const component=fs.readFileSync(new URL('../src/components/sections/MainCategoryProductSections.tsx',import.meta.url),'utf8');
assert.ok(!component.includes('scrollIntoView'));
assert.ok(component.includes('sticky z-40'));
assert.ok(component.includes("top:'var(--top-nav-height, 68px)'"));
const company=fs.readFileSync(new URL('../src/pages/CompanyProducts.tsx',import.meta.url),'utf8');
assert.ok(company.includes('level="sub"'));
console.log('PASS: RTL/LTR horizontal-only centering, no ancestor scroll, sticky chips, company subcategories');
